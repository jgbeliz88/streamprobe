import { spawnSync } from "node:child_process";
import { cpSync, existsSync, rmSync, writeFileSync } from "node:fs";
import { networkInterfaces } from "node:os";
import path from "node:path";

// Server-side helpers shared by the Deploy TV routes (deploy and diagnosis):
// they look at this machine's network and at the TV toolchains installed on it.

export function lanIp(): string {
  const nets = networkInterfaces();
  for (const list of Object.values(nets)) {
    for (const ni of list || []) {
      if (ni.family === "IPv4" && !ni.internal) return ni.address;
    }
  }
  return "";
}

export function hasTool(name: string): boolean {
  try {
    return spawnSync("which", [name], { encoding: "utf8" }).status === 0;
  } catch {
    return false;
  }
}

/**
 * Locate the Android SDK. The gradle build needs it, and the dev server may
 * have been started from a shell with no ANDROID_HOME set, so look in the usual
 * install locations too (Homebrew cask and Android Studio).
 */
export function androidSdkDir(): string {
  const candidates = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    "/opt/homebrew/share/android-commandlinetools",
    "/usr/local/share/android-commandlinetools",
    process.env.HOME ? path.join(process.env.HOME, "Library/Android/sdk") : undefined,
  ].filter(Boolean) as string[];
  for (const dir of candidates) {
    if (existsSync(path.join(dir, "platforms")) || existsSync(path.join(dir, "platform-tools"))) {
      return dir;
    }
  }
  return "";
}

/**
 * The device NAME that `sdb devices` reports for this TV (e.g. TQ55QN90DATXXC).
 * `tizen install -t` matches on that name, so handing it the IP fails with
 * "There is no connected target" even while sdb shows the device attached.
 * Falls back to the IP when the listing can't be read.
 */
export function sdbDeviceName(tvIp: string): string {
  try {
    const out = spawnSync("sdb", ["devices"], { encoding: "utf8" }).stdout || "";
    for (const line of out.split("\n")) {
      const m = line.trim().match(/^(\S+)\s+device\s+(\S+)$/);
      if (!m) continue;
      if (!tvIp || m[1].startsWith(tvIp)) return m[2];
    }
  } catch {
    /* fall through to the IP */
  }
  return tvIp;
}

/**
 * Stage a webOS app that carries the StreamProbe UI itself (the static export
 * in .next-tv, from scripts/tv-export.mjs) instead of redirecting to the Mac.
 *
 * Why: the TV runtime only exposes EME (DRM) to a secure origin. http://<mac>
 * is not one, file:// inside an installed app is. The UI still uses the Mac for
 * the proxy and traces, through `?api=`, over the LAN only.
 *
 * `launchUrl` is the hosted URL the panel built (http://<mac>/?url=…); its query
 * is kept and `api` added. Returns the staging directory to hand to ares-package.
 */
export function stageWebosPackaged(root: string, launchUrl: string, macHost: string): string {
  const src = path.join(root, "tv-launchers", "webos");
  const ui = path.join(root, ".next-tv");
  if (!existsSync(path.join(ui, "index.html"))) {
    throw new Error("Falta la UI estática (.next-tv): ejecuta node scripts/tv-export.mjs");
  }
  const stage = path.join(root, "tv-launchers", "dist", "webos-stage");
  rmSync(stage, { recursive: true, force: true });
  // appinfo.json + icons; the hosted launcher's index.html is replaced below.
  cpSync(src, stage, {
    recursive: true,
    filter: (p) => !path.basename(p).startsWith(".") && path.basename(p) !== "index.html",
  });
  cpSync(ui, path.join(stage, "app"), { recursive: true });

  const q = new URL(launchUrl).searchParams;
  q.set("api", `http://${macHost.replace(/^https?:\/\//, "").replace(/\/+$/, "")}`);
  const target = `app/index.html?${q.toString()}`;
  writeFileSync(
    path.join(stage, "index.html"),
    `<!DOCTYPE html>
<html>
  <head>
    <meta charset="utf-8" />
    <title>StreamProbe</title>
    <script>
      // Generated by Deploy TV: open the UI packaged in this app (file:// is a
      // secure origin, so DRM works). The Mac is only the API server (?api=).
      window.location.replace(${JSON.stringify(target)});
    </script>
  </head>
  <body></body>
</html>
`
  );
  return stage;
}
